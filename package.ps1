# Builds the release zip for GitHub Releases: noti-fai-windows-x64.zip
# Layout matches what install.ps1 expects.
$ErrorActionPreference = 'Stop'
Set-Location $PSScriptRoot

cargo build --release
if ($LASTEXITCODE) { throw 'cargo build failed' }
# Set CARGO_TARGET_DIR to a short path if linking fails on a long folder path.
$target = if ($env:CARGO_TARGET_DIR) { $env:CARGO_TARGET_DIR } else { 'target' }
Copy-Item "$target\release\noti-fai.exe" dist\ -Force

$stage = Join-Path $env:TEMP 'noti-fai-release'
Remove-Item $stage -Recurse -Force -ErrorAction SilentlyContinue
New-Item -ItemType Directory "$stage\noti-fai" | Out-Null
Copy-Item dist, extension, install.ps1, README.md, LICENSE -Destination "$stage\noti-fai" -Recurse
Get-ChildItem "$stage\noti-fai\dist" -Filter *.json | Remove-Item  # generated by install.ps1

$zip = Join-Path $PSScriptRoot 'noti-fai-windows-x64.zip'
Remove-Item $zip -ErrorAction SilentlyContinue
Compress-Archive -Path "$stage\noti-fai" -DestinationPath $zip
"Created $zip"
