# Builds the release zip for GitHub Releases: ballpop-windows-x64.zip
# Layout matches what install.ps1 expects.
$ErrorActionPreference = 'Stop'
Set-Location $PSScriptRoot

cargo build --release
Copy-Item target\release\ballpop.exe dist\ -Force

$stage = Join-Path $env:TEMP 'ballpop-release'
Remove-Item $stage -Recurse -Force -ErrorAction SilentlyContinue
New-Item -ItemType Directory "$stage\ballpop" | Out-Null
Copy-Item dist, extension, install.ps1, README.md, LICENSE -Destination "$stage\ballpop" -Recurse
Get-ChildItem "$stage\ballpop\dist" -Filter *.json | Remove-Item  # generated by install.ps1

$zip = Join-Path $PSScriptRoot 'ballpop-windows-x64.zip'
Remove-Item $zip -ErrorAction SilentlyContinue
Compress-Archive -Path "$stage\ballpop" -DestinationPath $zip
"Created $zip"
